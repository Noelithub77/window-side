//! Generates boot files from the detected running entry, without touching the host.
use crate::detect::boot::{BootProfile, Initramfs, Loader, bls_path, running_bls, safe_name};
use crate::setup::files::{self, SystemFile};
use anyhow::{Result, bail};

pub const GRUB_SCRIPT: &str = "/etc/grub.d/41_window_side";
pub const GRUB_DEFAULTS: &str = "/etc/default/grub.d/70-window-side.cfg";
pub const INITRAMFS_MODULES: &str = "/etc/initramfs-tools/modules";
pub const DRACUT_CONF: &str = "/etc/dracut.conf.d/70-window-side-vfio.conf";

pub fn validate(profile: &BootProfile) -> Result<()> {
    if !safe_name(&profile.kernel) { bail!("Invalid boot kernel"); }
    let valid = match (profile.loader, profile.initramfs) {
        (Loader::Limine, Initramfs::Mkinitcpio) => profile.source == "/etc/default/limine" && profile.contents.is_empty(),
        (Loader::Grub, Initramfs::Tools) => profile.source == "/boot/grub/grub.cfg" && profile.entry == "window-side-normal"
            && !profile.contents.contains("\nWS_BOOT_ENTRY\n") && !profile.contents.contains("menuentry "),
        (Loader::Grub, Initramfs::Dracut) | (Loader::SystemdBoot, _) => bls_path(&profile.source)
            && safe_name(&profile.entry) && running_bls(&profile.contents, &profile.kernel),
        _ => false,
    };
    if !valid { bail!("Unsupported boot entry; no GPU profile on this boot loader"); }
    Ok(())
}

fn file(path: &str, contents: String, mode: u32) -> SystemFile {
    SystemFile { path: path.into(), contents, mode }
}

pub fn bls_twin(entry: &str, cmdline: &str, gpu: bool) -> String {
    entry.lines().filter(|line| !line.starts_with("# window-side")).map(|line| {
        if line.starts_with("options ") || line.starts_with("options\t") { format!("options {cmdline}") }
        else if gpu && (line.starts_with("title ") || line.starts_with("title\t")) { "title Windows GPU passthrough".into() }
        else if gpu && (line.starts_with("id ") || line.starts_with("id\t")) { "id window-side-gpu".into() }
        else { line.to_owned() }
    }).collect::<Vec<_>>().join("\n") + "\n"
}

fn grub_body(body: &str, cmdline: &str) -> String {
    let cmdline = cmdline.split_whitespace().map(|token| {
        let escaped = token.replace('\\', "\\\\").replace('"', "\\\"").replace('$', "\\$").replace('`', "\\`");
        format!("\"{escaped}\"")
    }).collect::<Vec<_>>().join(" ");
    body.lines().map(|line| {
        let parts: Vec<_> = line.split_whitespace().collect();
        if matches!(parts.first(), Some(&"linux" | &"linuxefi")) && parts.len() >= 2 {
            format!("    {} {} {cmdline}", parts[0], parts[1])
        } else { line.to_owned() }
    }).collect::<Vec<_>>().join("\n")
}

pub fn generate(profile: &BootProfile, gpu_cmdline: &str, iommu: &str, current_modules: &str) -> Result<Vec<SystemFile>> {
    validate(profile)?;
    if profile.loader == Loader::Limine {
        return Ok(files::gpu_files(gpu_cmdline, iommu, &profile.kernel));
    }
    let normal = files::normal_cmdline(gpu_cmdline, iommu);
    let mut files = match profile.initramfs {
        Initramfs::Mkinitcpio => vec![file(files::MKINITCPIO_CONF, "MODULES+=(vfio_pci vfio_iommu_type1)\n".into(), 0o644)],
        Initramfs::Dracut => vec![file(DRACUT_CONF, "# Generated by ws setup; devices are claimed only by the GPU entry.\nforce_drivers+=\" vfio_pci vfio_iommu_type1 \"\nhostonly_cmdline=\"no\"\n".into(), 0o644)],
        Initramfs::Tools => {
            let mut modules = current_modules.trim_end().to_owned();
            for name in ["vfio_pci", "vfio_iommu_type1"] {
                if !current_modules.lines().any(|line| line.split_whitespace().next() == Some(name)) {
                    modules.push_str(&format!("\n{name}"));
                }
            }
            vec![file(INITRAMFS_MODULES, modules + "\n", 0o644)]
        }
    };
    if profile.source == "/boot/grub/grub.cfg" {
        let normal_body = grub_body(&profile.contents, &normal);
        let gpu_body = grub_body(&profile.contents, gpu_cmdline);
        let script = format!("#!/bin/sh\n# Generated by ws setup from the running kernel entry.\ncat <<'WS_BOOT_ENTRY'\nmenuentry 'Linux (window-side normal)' --id window-side-normal {{\n{normal_body}\n}}\nmenuentry 'Windows GPU passthrough' --id window-side-gpu {{\n{gpu_body}\n}}\nWS_BOOT_ENTRY\n");
        files.push(file(GRUB_SCRIPT, script, 0o755));
        files.push(file(GRUB_DEFAULTS, format!("# Generated by ws setup; normal Linux entries keep their GPU.\nGRUB_CMDLINE_LINUX=\"$GRUB_CMDLINE_LINUX {iommu} iommu=pt\"\n"), 0o644));
    } else {
        let parent = std::path::Path::new(&profile.source).parent().ok_or_else(|| anyhow::anyhow!("Missing boot entry directory"))?;
        let gpu_path = parent.join("window-side-gpu.conf");
        files.push(file(&profile.source, bls_twin(&profile.contents, &normal, false), 0o644));
        let original = std::path::Path::new(&profile.source).file_name().ok_or_else(|| anyhow::anyhow!("Missing original boot filename"))?.to_string_lossy();
        let twin = format!("# window-side-source: {original}\n{}", bls_twin(&profile.contents, gpu_cmdline, true));
        files.push(file(&gpu_path.to_string_lossy(), twin, 0o644));
    }
    Ok(files)
}

/// Rebuild the detected initramfs only, then register the twin with the loader.
pub fn apply(profile: &BootProfile) -> Result<(String, String)> {
    use crate::process::text;
    match profile.initramfs {
        Initramfs::Tools => { text("update-initramfs", &["-u", "-k", &profile.kernel])?; }
        Initramfs::Dracut => { text("dracut", &["--force", "--kver", &profile.kernel])?; }
        Initramfs::Mkinitcpio => { text("mkinitcpio", &["-P"])?; }
    }
    match profile.loader {
        Loader::Grub if profile.initramfs == Initramfs::Tools => {
            text("update-grub", &[])?;
            Ok(("grub:window-side-normal".into(), "grub:window-side-gpu".into()))
        }
        Loader::Grub => {
            // grubby keeps Fedora's normal BLS entry and its bookkeeping in sync.
            let contents = std::fs::read_to_string(&profile.source)?;
            let options = crate::detect::boot::bls_value(&contents, "options").ok_or_else(|| anyhow::anyhow!("Missing normal BLS options"))?;
            text("grubby", &[&format!("--update-kernel=TITLE={}", crate::detect::boot::bls_value(&profile.contents, "title").ok_or_else(|| anyhow::anyhow!("Missing BLS title"))?), &format!("--args={options}")])?;
            Ok((format!("grub:{}", profile.entry), "grub:window-side-gpu".into()))
        }
        Loader::SystemdBoot => Ok((format!("systemd-boot:{}", profile.entry), "systemd-boot:window-side-gpu.conf".into())),
        Loader::Limine => bail!("Limine uses its existing entry tool"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::detect::boot::{bls_value, grub_entry};

    fn profile(loader: Loader, initramfs: Initramfs, source: &str, kernel: &str, contents: &str) -> BootProfile {
        BootProfile { loader, initramfs, source: source.into(), kernel: kernel.into(),
            contents: contents.into(), entry: if source.ends_with("grub.cfg") { "window-side-normal".into() } else { "linux.conf".into() } }
    }
    const GPU: &str = "root=UUID=test rw quiet intel_iommu=on iommu=pt vfio-pci.ids=10de:1234 rd.driver.pre=vfio-pci";

    #[test]
    fn grub_twins_preserve_search_and_the_running_kernel() -> Result<()> {
        let config = include_str!("../../tests/fixtures/boot/grub.cfg");
        let body = grub_entry(config, "6.8.0-71-generic").ok_or_else(|| anyhow::anyhow!("Missing fixture entry"))?;
        assert!(grub_entry(config, "6.8.0-70-generic").is_none());
        let boot = profile(Loader::Grub, Initramfs::Tools, "/boot/grub/grub.cfg", "6.8.0-71-generic", &body);
        let files = generate(&boot, GPU, "intel_iommu=on", "# Existing modules\next4\n")?;
        let script = &files.iter().find(|file| file.path == GRUB_SCRIPT).ok_or_else(|| anyhow::anyhow!("Missing script"))?.contents;
        assert_eq!(script.matches("search --no-floppy").count(), 4);
        assert_eq!(script.matches("initrd /boot/initrd.img-6.8.0-71-generic").count(), 2);
        let (normal, gpu) = script.split_once("menuentry 'Windows GPU passthrough'").ok_or_else(|| anyhow::anyhow!("Missing twin"))?;
        assert!(!normal.contains("vfio-pci.ids="));
        assert!(gpu.contains("\"vfio-pci.ids=10de:1234\""));
        assert!(files.iter().any(|file| file.path == INITRAMFS_MODULES && file.contents == "# Existing modules\next4\nvfio_pci\nvfio_iommu_type1\n"));
        Ok(())
    }

    #[test]
    fn bls_twins_preserve_all_initrds_and_metadata() -> Result<()> {
        for (loader, initramfs, fixture, kernel) in [
            (Loader::Grub, Initramfs::Dracut, include_str!("../../tests/fixtures/boot/fedora.conf"), "6.14.1-300.fc42.x86_64"),
            (Loader::SystemdBoot, Initramfs::Mkinitcpio, include_str!("../../tests/fixtures/boot/systemd.conf"), "6.15.1-arch1-1"),
        ] {
            let boot = profile(loader, initramfs, "/boot/loader/entries/linux.conf", kernel, fixture);
            let files = generate(&boot, GPU, "intel_iommu=on", "")?;
            let normal = &files.iter().find(|file| file.path == boot.source).ok_or_else(|| anyhow::anyhow!("Missing normal"))?.contents;
            let gpu = &files.iter().find(|file| file.path.ends_with("window-side-gpu.conf")).ok_or_else(|| anyhow::anyhow!("Missing GPU"))?.contents;
            assert!(!normal.contains("vfio-pci.ids="));
            assert_eq!(bls_value(gpu, "options"), Some(GPU));
            for line in fixture.lines().filter(|line| line.starts_with("initrd ") || line.starts_with("linux ")) {
                assert!(normal.contains(line)); assert!(gpu.contains(line));
            }
        }
        Ok(())
    }

    #[test]
    fn only_the_detected_normal_entry_can_extend_the_allowlist() {
        let boot = profile(Loader::SystemdBoot, Initramfs::Mkinitcpio, "/boot/loader/entries/linux.conf", "6.15.1-arch1-1", include_str!("../../tests/fixtures/boot/systemd.conf"));
        assert!(files::allowed_path(&boot.source, Some(&boot)));
        assert!(!files::allowed_path("/boot/loader/entries/other.conf", Some(&boot)));
        assert!(!files::allowed_path(&boot.source, None));
        assert!(!files::allowed_path("/etc/sudoers", Some(&boot)));
    }

    #[test]
    fn unsupported_entries_and_paths_are_refused() {
        assert!(!bls_path("/boot/loader/entries/../../evil.conf"));
        assert!(!bls_path("/etc/loader/entries/linux.conf"));
        assert!(!running_bls("efi /EFI/Linux/linux.efi\noptions root=x", "6.8"));
        assert!(!running_bls("linux /vmlinuz-6.8\ninitrd /initrd\noptions $kernelopts", "6.8"));
        assert!(!running_bls(include_str!("../../tests/fixtures/boot/fedora.conf"), "other"));
    }

    #[test]
    fn limine_output_keeps_existing_tools_and_paths() -> Result<()> {
        let boot = profile(Loader::Limine, Initramfs::Mkinitcpio, "/etc/default/limine", "linux-omarchy", "");
        let files = generate(&boot, GPU, "intel_iommu=on", "")?;
        assert_eq!(files, files::gpu_files(GPU, "intel_iommu=on", "linux-omarchy"));
        let config = include_str!("../../tests/fixtures/boot/limine.conf");
        assert_eq!(crate::setup::root::entry_path(config, "window-side-gpu").as_deref(), Some("Omarchy/window-side-gpu"));
        Ok(())
    }
}
