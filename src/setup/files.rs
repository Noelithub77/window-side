//! System files setup installs as root. Every path here is on the root side's allowlist.
use serde::{Deserialize, Serialize};

pub const LIMINE_CONF: &str = "/etc/limine-entry-tool.d/70-window-side.conf";
pub const MKINITCPIO_CONF: &str = "/etc/mkinitcpio.conf.d/window-side-vfio.conf";
pub const PACMAN_HOOK: &str = "/etc/pacman.d/hooks/95-window-side-gpu-entry.hook";
pub const TMPFILES_CONF: &str = "/etc/tmpfiles.d/10-window-side-looking-glass.conf";
pub const UDEV_RULE: &str = "/etc/udev/rules.d/70-window-side.rules";
pub const DISK_SCRIPT: &str = "/usr/local/lib/window-side/virtual-disk";
pub const DISK_SERVICE: &str = "/etc/systemd/system/window-side-disk.service";
pub const GPU_ENTRY: &str = "window-side-gpu";

pub const ALLOWED: &[&str] = &[LIMINE_CONF, MKINITCPIO_CONF, PACMAN_HOOK, TMPFILES_CONF, UDEV_RULE, DISK_SCRIPT, DISK_SERVICE];

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct SystemFile {
    pub path: String,
    pub contents: String,
    pub mode: u32,
}

fn file(path: &str, contents: String, mode: u32) -> SystemFile {
    SystemFile { path: path.to_owned(), contents, mode }
}

/// Kernel command line for the GPU entry: the current one with vfio claiming the GPU first.
pub fn gpu_cmdline(current: &str, iommu_flag: &str, ids: &[String], driver: Option<&str>) -> String {
    let ours = |token: &str| {
        token.starts_with("BOOT_IMAGE=")
            || token.starts_with("vfio-pci.ids=")
            || token.starts_with("rd.driver.pre=vfio")
            || token.starts_with("modprobe.blacklist=")
            || token.starts_with("intel_iommu=")
            || token.starts_with("amd_iommu=")
            || token.starts_with("iommu=")
    };
    let mut tokens: Vec<String> = current.split_whitespace().filter(|token| !ours(token)).map(str::to_owned).collect();
    tokens.extend([iommu_flag.to_owned(), "iommu=pt".to_owned(), format!("vfio-pci.ids={}", ids.join(",")), "rd.driver.pre=vfio-pci".to_owned()]);
    // NVIDIA's driver grabs the GPU before vfio-pci unless it is kept out of this boot.
    if matches!(driver, Some("nvidia" | "nouveau")) {
        tokens.push("modprobe.blacklist=nvidia,nvidia_drm,nvidia_modeset,nvidia_uvm,nouveau".to_owned());
    }
    tokens.join(" ")
}

/// Limine names unified kernel images `<os>_<kernel>.efi` under the ESP.
pub fn uki_glob(kernel: &str) -> String {
    format!("/boot/EFI/Linux/*_{kernel}.efi")
}

pub fn gpu_files(cmdline: &str, iommu_flag: &str, kernel: &str) -> Vec<SystemFile> {
    let uki = uki_glob(kernel);
    vec![
        file(LIMINE_CONF, format!(
            "# Generated by ws setup. The normal entry keeps the host GPU driver; IOMMU is on for both.\n\
             KERNEL_CMDLINE[default]+=\" {iommu_flag} iommu=pt\"\n\
             # The GPU entry hands the passthrough GPU to vfio-pci before host drivers load.\n\
             KERNEL_CMDLINE[{GPU_ENTRY}]=\"{cmdline}\"\n"
        ), 0o644),
        file(MKINITCPIO_CONF, "# Generated by ws setup: only the GPU entry claims devices.\nMODULES+=(vfio_pci vfio_iommu_type1)\n".to_owned(), 0o644),
        file(PACMAN_HOOK, format!(
            "# Generated by ws setup: re-adds the GPU entry whenever the kernel image is rebuilt.\n\
             [Trigger]\nType = Path\nOperation = Install\nOperation = Upgrade\nTarget = usr/lib/modules/*/vmlinuz\nTarget = usr/lib/initcpio/*\n\n\
             [Trigger]\nType = Package\nOperation = Install\nOperation = Upgrade\nTarget = mkinitcpio\n\n\
             [Action]\nDescription = Updating the window-side GPU boot entry...\nWhen = PostTransaction\nDepends = limine-mkinitcpio-hook\n\
             Exec = /usr/bin/sh -c 'for uki in {uki}; do [ -f \"$uki\" ] && limine-entry-tool --add-uki {GPU_ENTRY} \"$uki\" --comment \"{kernel} with GPU passthrough\"; break; done; exit 0'\n"
        ), 0o644),
    ]
}

pub fn looking_glass_file(user: &str) -> SystemFile {
    file(TMPFILES_CONF, format!("# Generated by ws setup: Looking Glass frame buffer for {user}.\nf /dev/shm/looking-glass 0660 {user} kvm -\n"), 0o644)
}

/// Whole-drive mode: lets system libvirt open only the Windows drive.
pub fn udev_file(serial: &str, group: &str) -> SystemFile {
    file(UDEV_RULE, format!(
        "# Generated by ws setup: the Windows drive, for system libvirt only.\n\
         SUBSYSTEM==\"block\", ENV{{DEVTYPE}}==\"disk\", ENV{{ID_SERIAL}}==\"{serial}\", GROUP=\"{group}\", MODE=\"0660\"\n"
    ), 0o644)
}

/// Partition mode: joins the boot image and the real Windows partition into one disk at boot.
pub fn virtual_disk_files(windows_part_uuid: &str, header_sectors: u64, windows_sectors: u64, footer_sectors: u64) -> Vec<SystemFile> {
    let footer_start = header_sectors + windows_sectors;
    let script = format!(
        r#"#!/bin/sh
# Generated by ws setup. Windows sees a disk made of a boot image and its real
# partition; the other partitions on this drive are never exposed to the VM.
set -eu
dir=/var/lib/window-side
case "${{1:-}}" in
start)
  windows=$(readlink -f /dev/disk/by-partuuid/{windows_part_uuid})
  [ "$(blockdev --getsz "$windows")" = {windows_sectors} ] || {{ echo 'The Windows partition changed size; run ws setup again.' >&2; exit 1; }}
  header=$(losetup --find --show "$dir/header.img")
  footer=$(losetup --find --show "$dir/footer.img")
  printf '0 {header_sectors} linear %s 0\n{header_sectors} {windows_sectors} linear %s 0\n{footer_start} {footer_sectors} linear %s 0\n' \
    "$header" "$windows" "$footer" | dmsetup create window-side
  ;;
stop)
  dmsetup remove window-side 2>/dev/null || true
  for image in header footer; do
    losetup -n -O NAME -j "$dir/$image.img" | while read -r device; do losetup -d "$device"; done
  done
  ;;
*) echo 'Usage: virtual-disk start|stop' >&2; exit 2 ;;
esac
"#
    );
    let service = format!(
        "# Generated by ws setup.\n[Unit]\nDescription=Assemble the window-side virtual Windows disk\n\
         After=local-fs.target\nBefore=libvirtd.service virtqemud.service\n\n\
         [Service]\nType=oneshot\nRemainAfterExit=yes\nExecStart={DISK_SCRIPT} start\nExecStop={DISK_SCRIPT} stop\n\n\
         [Install]\nWantedBy=multi-user.target\n"
    );
    vec![file(DISK_SCRIPT, script, 0o755), file(DISK_SERVICE, service, 0o644)]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gpu_cmdline_replaces_old_passthrough_tokens() {
        let current = "BOOT_IMAGE=/vmlinuz root=/dev/mapper/root rw quiet intel_iommu=on iommu=pt vfio-pci.ids=1:2 rd.driver.pre=vfio-pci";
        let ids = ["10de:28a0".to_owned(), "10de:22be".to_owned()];
        assert_eq!(
            gpu_cmdline(current, "intel_iommu=on", &ids, Some("vfio-pci")),
            "root=/dev/mapper/root rw quiet intel_iommu=on iommu=pt vfio-pci.ids=10de:28a0,10de:22be rd.driver.pre=vfio-pci"
        );
        assert!(gpu_cmdline("root=x", "amd_iommu=on", &ids, Some("nvidia")).ends_with("nouveau"));
    }

    #[test]
    fn virtual_disk_table_is_contiguous() {
        let files = virtual_disk_files("w-1", 264192, 1000, 2048);
        let script = &files[0].contents;
        assert!(script.contains("0 264192 linear %s 0\\n264192 1000 linear %s 0\\n265192 2048 linear %s 0"));
        assert!(script.contains("by-partuuid/w-1"));
        assert!(files.iter().all(|file| ALLOWED.contains(&file.path.as_str())));
    }
}
