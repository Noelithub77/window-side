#!/usr/bin/env bash
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
if [[ "${1:-}" == --help || "${1:-}" == -h || "${2:-}" == --help || "${2:-}" == -h ]]; then
  cat <<'HELP'
Usage: ./ops icons | ./ops icons:check

Generate tracked application and tray PNGs from icons/source/window-side.svg,
plus the viewer's window icon and splash logo in third_party/looking-glass.
icons:check compares a temporary render and does not change tracked files.
Requires the development tools rsvg-convert (librsvg) and magick (ImageMagick).
HELP
  exit 0
fi
mode=${1:-generate}
[[ $# -le 1 && ( "$mode" == generate || "$mode" == check ) ]] || { echo 'Usage: ./ops icons[:check]' >&2; exit 2; }
command -v rsvg-convert >/dev/null || { echo 'Icon generation/checking needs the dev tool rsvg-convert (librsvg)' >&2; exit 1; }
command -v magick >/dev/null || { echo 'Icon generation/checking needs the dev tool magick (ImageMagick)' >&2; exit 1; }
stage=$(mktemp -d)
trap 'rm -rf -- "$stage"' EXIT
for size in 16 22 24 32 48 64 128 256 512; do
  directory="$stage/hicolor/${size}x${size}/apps"
  mkdir -p "$directory"
  # Tauri requires RGBA even when the artwork is fully opaque.
  rsvg-convert --width "$size" --height "$size" "$root/icons/source/window-side.svg" |
    magick png:- -strip "PNG32:$directory/window-side.png"
done
mkdir -p "$stage/hicolor/scalable/apps"
cp "$root/icons/source/window-side.svg" "$stage/hicolor/scalable/apps/window-side.svg"
cp "$stage/hicolor/512x512/apps/window-side.png" "$stage/icon.png"
# The viewer's splash draws its own background, so its logo is the tiles alone,
# cropped to them. nanosvg renders it; keep the source to plain shapes and gradients.
viewer="$stage/looking-glass"
mkdir -p "$viewer"
sed -e '/<rect width="1024" height="1024"/d' \
  -e 's/width="1024" height="1024" viewBox="0 0 1024 1024"/width="576" height="576" viewBox="224 224 576 576"/' \
  "$root/icons/source/window-side.svg" > "$viewer/window-side-logo.svg"
grep -q 'viewBox="224 224 576 576"' "$viewer/window-side-logo.svg" && ! grep -q 'width="1024"' "$viewer/window-side-logo.svg" ||
  { echo 'icons/source/window-side.svg changed shape; update the viewer logo crop in scripts/icons.sh' >&2; exit 1; }
# Looking Glass sends this 64 px icon to the compositor as straight ARGB words.
{
  echo '/* Generated by scripts/icons.sh from icons/source/window-side.svg. */'
  echo
  echo '#define LG_ICON_WIDTH  0x40'
  echo '#define LG_ICON_HEIGHT 0x40'
  echo
  echo '#define LG_ICON_PIXELS \'
  rsvg-convert --width 64 --height 64 "$root/icons/source/window-side.svg" |
    magick png:- -depth 8 rgba:- | od -An -v -tu1 -w4 |
    awk '{ words[NR] = sprintf("0x%02x%02x%02x%02x", $4, $1, $2, $3) }
      END { for (i = 1; i <= NR; i += 8) {
        line = "  "; for (j = i; j < i + 8 && j <= NR; j++) line = line words[j] (j < NR ? ", " : "")
        sub(/ $/, "", line); print line (i + 8 <= NR ? " \\" : "") } }'
} > "$viewer/icondata.h"
if [[ "$mode" == check ]]; then
  diff -qr "$stage/hicolor" "$root/icons/hicolor"
  cmp "$stage/icon.png" "$root/icons/icon.png"
  for file in window-side-logo.svg icondata.h; do cmp "$viewer/$file" "$root/third_party/looking-glass/resources/$file"; done
  echo 'Generated icons match the SVG sources'
else
  cp "$viewer/window-side-logo.svg" "$viewer/icondata.h" "$root/third_party/looking-glass/resources/"
  rm -r -- "$viewer"
  cp -R "$stage/." "$root/icons/"
  echo 'Regenerated application and tray icons'
fi
